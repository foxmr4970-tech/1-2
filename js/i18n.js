const sw = document.createElement("div");
sw.id = "lang-switch";
sw.innerHTML = `<button type="button" data-l="ru">Рус</button><button type="button" data-l="ky">Кыр</button>`;
document.querySelector(".header-inner").appendChild(sw);

function setLang(l) {
  lang = l;
  try {
    localStorage.setItem("lang", l);
  } catch (e) {}
  document.documentElement.lang = l;
  sw.querySelectorAll("button").forEach((b) => b.classList.toggle("active", b.dataset.l === l));
  if (l === "ky") {
    applyTo(document.body);
    document.title = toKy(ruTitle);
  } else {
    restoreRu();
  }
}

sw.addEventListener("click", (e) => {
  const b = e.target.closest("button");
  if (b) setLang(b.dataset.l);
});

setLang(lang);