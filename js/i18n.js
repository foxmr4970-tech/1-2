// ======== Перевод одной строки ========
function toKy(s) {
  const lead = s.match(/^\s*/)[0];
  const trail = s.match(/\s*$/)[0];
  let core = s.trim().replace(/\s+/g, " ");
  if (core === "") return s;
  if (KY_EXACT[core]) return lead + KY_EXACT[core] + trail;
  for (const [ru, ky] of KY_PARTS) {
    if (core.includes(ru)) core = core.split(ru).join(ky);
  }
  return lead + core + trail;
}

// ======== Подмена текста на странице ========
let lang = "ru";
try {
  lang = localStorage.getItem("lang") === "ky" ? "ky" : "ru";
} catch (e) {}

const textRec = new WeakMap(); // текстовый узел -> {ru, ky}
const attrRec = new WeakMap(); // поле ввода -> {ru, ky}
const ruTitle = document.title;

function translateText(n) {
  const p = n.parentElement;
  if (!p || p.closest("script, style, #lang-switch")) return;
  const rec = textRec.get(n);
  if (rec && n.nodeValue === rec.ky) return; // уже переведено нами
  const ru = n.nodeValue;
  const ky = toKy(ru);
  if (ky === ru) return;
  textRec.set(n, { ru, ky });
  n.nodeValue = ky;
}

function translateAttr(el) {
  const cur = el.getAttribute("placeholder");
  if (cur === null) return;
  const rec = attrRec.get(el);
  if (rec && cur === rec.ky) return;
  const ky = toKy(cur);
  if (ky === cur) return;
  attrRec.set(el, { ru: cur, ky });
  el.setAttribute("placeholder", ky);
}

function applyTo(root) {
  if (root.nodeType === 3) return translateText(root);
  if (root.nodeType !== 1) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let n;
  while ((n = walker.nextNode())) nodes.push(n);
  nodes.forEach(translateText);
  if (root.matches("[placeholder]")) translateAttr(root);
  root.querySelectorAll("[placeholder]").forEach(translateAttr);
}

function restoreRu() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = walker.nextNode())) {
    const r = textRec.get(n);
    if (r && n.nodeValue === r.ky) n.nodeValue = r.ru;
    textRec.delete(n);
  }
  document.querySelectorAll("[placeholder]").forEach((el) => {
    const r = attrRec.get(el);
    if (r && el.getAttribute("placeholder") === r.ky) el.setAttribute("placeholder", r.ru);
    attrRec.delete(el);
  });
  document.title = ruTitle;
}

// Переводим то, что создаётся позже (результаты расчётов, подсказки, новые строки)
new MutationObserver((muts) => {
  if (lang !== "ky") return;
  for (const m of muts) {
    if (m.type === "childList") m.addedNodes.forEach(applyTo);
    else if (m.type === "characterData") translateText(m.target);
    else if (m.type === "attributes") translateAttr(m.target);
  }
}).observe(document.body, {
  childList: true,
  subtree: true,
  characterData: true,
  attributes: true,
  attributeFilter: ["placeholder"],
});

